// Builds the design-system token outputs from the DTCG source.
// Input:  src/design-system/tokens/tokens.json
// Output: src/design-system/tokens/tokens.css (CSS variables + Tailwind @theme inline)
//         src/design-system/tokens/tokens.js  (resolved values for charts and JS)
// Run with `npm run tokens`. The drift test fails when the outputs are stale.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'

const HEADER = 'Generated by scripts/build-tokens.mjs - do not edit. Source: tokens.json, run npm run tokens.'
const REF = /\{([^{}]+)\}/g
const DEFAULT_THEME = 'light'

// Tailwind theme keys. Names are chosen so they never replace a Tailwind default:
// Tailwind looks up `--spacing-*` before `--container-*` for max-w-*, so `--spacing-md`
// would turn max-w-md into 16px; `--radius-lg`, `--ease-out` and friends would change
// rounded-lg and ease-out everywhere. Space gets a `ds-` prefix, radius and easing get
// semantic names, and font sizes and shadows use names Tailwind does not ship.
const RADIUS_THEME = { xs: 'tag', sm: 'input', md: 'control', lg: 'card', xl: 'sheet', xxl: 'panel', pill: 'chip' }
const EASING_THEME = { out: 'enter', in: 'exit', 'in-out': 'move' }
const COLOR_ROLE_GROUPS = ['surface', 'text', 'border', 'status', 'chart']
const TEXT_SHORT_ALIASES = ['primary', 'secondary', 'muted', 'faint', 'on-brand', 'link', 'brand']

function isToken(node) {
  return node !== null && typeof node === 'object' && '$value' in node
}

// Walks a group and returns tokens as { path: ['primitive', 'color', 'pink', '500'], value }.
function collect(node, path, out) {
  if (isToken(node)) {
    out.push({ path, value: String(node.$value) })
    return out
  }
  if (node === null || typeof node !== 'object') return out
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$')) continue
    collect(child, [...path, key], out)
  }
  return out
}

function varName(path) {
  const [tier, ...rest] = path
  if (tier === 'primitive') return `mv-${rest.join('-')}`
  if (tier === 'alias') return rest.join('-')
  if (tier === 'role') {
    const [, group, ...name] = rest
    if (group === 'shadcn') return name.join('-')
    return [group, ...name].join('-')
  }
  throw new Error(`Unknown token tier "${tier}" at ${path.join('.')}`)
}

export function buildTokens(source) {
  const all = collect(source, [], [])
  const byPath = new Map(all.map((t) => [t.path.join('.'), t]))

  const lookup = (ref, from) => {
    const target = byPath.get(ref)
    if (!target) throw new Error(`Token ${from.path.join('.')} references {${ref}}, which does not exist`)
    return target
  }

  const cssValue = (token) => token.value.replace(REF, (_, ref) => `var(--${varName(lookup(ref, token).path)})`)

  const resolved = new Map()
  const resolve = (token, stack = []) => {
    const key = token.path.join('.')
    if (resolved.has(key)) return resolved.get(key)
    if (stack.includes(key)) throw new Error(`Token reference cycle: ${[...stack, key].join(' -> ')}`)
    const value = token.value.replace(REF, (_, ref) => resolve(lookup(ref, token), [...stack, key]))
    resolved.set(key, value)
    return value
  }

  const tier = (name) => all.filter((t) => t.path[0] === name)
  const roles = (theme) => all.filter((t) => t.path[0] === 'role' && t.path[1] === theme)
  const themes = Object.keys(source.role ?? {}).filter((k) => !k.startsWith('$'))

  const decl = (name, value) => `  --${name}: ${value};`
  const block = (selector, tokens) => [`${selector} {`, ...tokens.map((t) => decl(varName(t.path), cssValue(t))), '}']

  // Every value is validated up front so a bad reference fails the build, not a later lookup.
  for (const t of all) resolve(t)

  const css = [`/* ${HEADER} */`, '']
  css.push(...block(':root', [...tier('primitive'), ...tier('alias'), ...roles(DEFAULT_THEME)]))
  for (const theme of themes.filter((t) => t !== DEFAULT_THEME)) {
    css.push('', ...block(`[data-theme="${theme}"]`, roles(theme)))
  }
  css.push('', '@theme inline {', ...themeEntries(all, byPath, cssValue).map(([k, v]) => decl(k, v)), '}', '')

  const jsTokens = {}
  for (const t of [...tier('primitive'), ...tier('alias'), ...roles(DEFAULT_THEME)]) {
    jsTokens[varName(t.path)] = resolve(t)
  }
  const chartColors = roles(DEFAULT_THEME)
    .filter((t) => t.path[2] === 'chart' && /^\d+$/.test(t.path[3]))
    .sort((a, b) => Number(a.path[3]) - Number(b.path[3]))
    .map((t) => resolve(t))

  const js = [
    `// ${HEADER}`,
    '',
    `export const tokens = ${JSON.stringify(jsTokens, null, 2)}`,
    '',
    `export const chartColors = ${JSON.stringify(chartColors, null, 2)}`,
    '',
  ].join('\n')

  return { css: css.join('\n'), js }
}

function themeEntries(all, byPath, cssValue) {
  const entries = []
  const lightRoles = all.filter((t) => t.path[0] === 'role' && t.path[1] === DEFAULT_THEME)
  const alias = (group) => all.filter((t) => t.path[0] === 'alias' && t.path[1] === group)

  for (const t of lightRoles) {
    const group = t.path[2]
    if (COLOR_ROLE_GROUPS.includes(group)) entries.push([`color-${varName(t.path)}`, `var(--${varName(t.path)})`])
  }
  const shortNames = new Set()
  for (const name of TEXT_SHORT_ALIASES) {
    if (byPath.has(`role.${DEFAULT_THEME}.text.${name}`)) {
      entries.push([`color-${name}`, `var(--text-${name})`])
      shortNames.add(name)
    }
  }
  // shadcn color keys that collide with the short text aliases (primary, secondary, muted)
  // stay CSS-only: text-primary means the primary text color in this system.
  for (const t of lightRoles) {
    if (t.path[2] !== 'shadcn') continue
    const name = varName(t.path)
    if (!shortNames.has(name)) entries.push([`color-${name}`, `var(--${name})`])
  }
  for (const t of alias('radius')) {
    const key = RADIUS_THEME[t.path[2]]
    if (key) entries.push([`radius-${key}`, `var(--${varName(t.path)})`])
  }
  for (const t of alias('space')) entries.push([`spacing-ds-${t.path[2]}`, `var(--${varName(t.path)})`])
  for (const t of alias('font-size')) entries.push([`text-${t.path[2]}`, `var(--${varName(t.path)})`])
  // Shadow keys share their alias names, so the value is written out (references still become
  // var()) instead of var(--shadow-card), which would point at itself.
  for (const t of alias('shadow')) entries.push([`shadow-${t.path[2]}`, cssValue(t)])
  for (const t of alias('easing')) {
    const key = EASING_THEME[t.path[2]]
    if (key) entries.push([`ease-${key}`, `var(--${varName(t.path)})`])
  }
  const sans = byPath.get('primitive.font.family.sans')
  if (sans) entries.push(['font-sans', `var(--${varName(sans.path)})`])
  return entries
}

export const TOKENS_DIR = new URL('../src/design-system/tokens/', import.meta.url)

function main() {
  const source = JSON.parse(readFileSync(new URL('tokens.json', TOKENS_DIR), 'utf8'))
  const { css, js } = buildTokens(source)
  writeFileSync(new URL('tokens.css', TOKENS_DIR), css)
  writeFileSync(new URL('tokens.js', TOKENS_DIR), js)
  console.log(`Wrote ${fileURLToPath(new URL('tokens.css', TOKENS_DIR))}`)
  console.log(`Wrote ${fileURLToPath(new URL('tokens.js', TOKENS_DIR))}`)
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main()
