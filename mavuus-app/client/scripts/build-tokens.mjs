// Builds the design-system token outputs from the DTCG source.
// Input:  src/design-system/tokens/tokens.json
// Output: src/design-system/tokens/tokens.css (CSS variables + Tailwind @theme inline)
//         src/design-system/tokens/tokens.js  (resolved light-theme values for charts and JS)
//         src/design-system/lib/twMergeConfig.js (theme scales so cn() merges token classes)
// Run with `npm run tokens`. The drift test fails when the outputs are stale.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'

const HEADER = 'Generated by scripts/build-tokens.mjs - do not edit. Source: tokens.json, run npm run tokens.'
const REF = /\{([^{}]+)\}/g
const DEFAULT_THEME = 'light'
const THEME_NAME = /^[a-z0-9-]+$/

// CSS variable names per tier:
//   primitive -> --mv-<path>       (--mv-color-pink-500)
//   alias     -> --ds-<path>       (--ds-space-md, --ds-radius-lg); the prefix keeps aliases out of
//                                  Tailwind's own theme namespaces (--radius-*, --shadow-*, --text-*)
//   role      -> --<group>-<name>  (--surface-raised, --text-primary)
//
// Tailwind theme keys. One color scheme, named after the role groups: bg-surface-*, text-text-*,
// border-border-*, bg-status-*, *-chart-*. Other keys never replace a Tailwind default:
// Tailwind looks up --spacing-* before --container-* for max-w-*, so --spacing-md would turn
// max-w-md into 16px, and --radius-lg or --ease-out would change rounded-lg and ease-out
// everywhere. Space gets a ds- prefix, radius and easing get semantic names, and font sizes and
// shadows use names Tailwind does not ship.
const RADIUS_THEME = { xs: 'tag', sm: 'input', md: 'control', lg: 'card', xl: 'sheet', xxl: 'panel', pill: 'chip' }
const EASING_THEME = { out: 'enter', in: 'exit', 'in-out': 'move' }
const COLOR_ROLE_GROUPS = ['surface', 'text', 'border', 'status', 'chart']

// Tailwind theme namespaces that tailwind-merge has a theme scale for (same names in both).
// Longer names first so --inset-shadow-* is not read as --shadow-*.
const MERGE_SCALES = [
  'inset-shadow',
  'drop-shadow',
  'text-shadow',
  'font-weight',
  'breakpoint',
  'container',
  'perspective',
  'tracking',
  'leading',
  'spacing',
  'animate',
  'aspect',
  'radius',
  'shadow',
  'color',
  'blur',
  'ease',
  'font',
  'text',
]

function isToken(node) {
  return node !== null && typeof node === 'object' && '$value' in node
}

// Walks a group and returns tokens as { path: ['primitive', 'color', 'pink', '500'], value }.
function collect(node, path, out) {
  if (isToken(node)) {
    const { $value } = node
    if (typeof $value !== 'string' && typeof $value !== 'number') {
      throw new Error(`Token ${path.join('.')} has a composite $value; only string or number values are supported`)
    }
    out.push({ path, value: String($value) })
    return out
  }
  if (node === null || typeof node !== 'object') return out
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$')) continue
    collect(child, [...path, key], out)
  }
  return out
}

function varName(path) {
  const [tier, ...rest] = path
  if (tier === 'primitive') return `mv-${rest.join('-')}`
  if (tier === 'alias') return `ds-${rest.join('-')}`
  if (tier === 'role') return rest.slice(1).join('-')
  throw new Error(`Unknown token tier "${tier}" at ${path.join('.')}`)
}

// Var names must be unique per scope: :root holds primitives, aliases and the light roles,
// and each other theme block holds its own roles.
function assertUnique(tokens, scope) {
  const seen = new Map()
  for (const t of tokens) {
    const name = varName(t.path)
    if (seen.has(name)) {
      throw new Error(`Tokens ${seen.get(name)} and ${t.path.join('.')} both emit --${name} in ${scope}`)
    }
    seen.set(name, t.path.join('.'))
  }
}

export function buildTokens(source) {
  const all = collect(source, [], [])
  const byPath = new Map(all.map((t) => [t.path.join('.'), t]))

  const themes = Object.keys(source.role ?? {}).filter((k) => !k.startsWith('$'))
  for (const theme of themes) {
    if (!THEME_NAME.test(theme)) throw new Error(`Theme name "${theme}" must match ${THEME_NAME}`)
  }

  const tier = (name) => all.filter((t) => t.path[0] === name)
  const roles = (theme) => all.filter((t) => t.path[0] === 'role' && t.path[1] === theme)
  const rootTokens = [...tier('primitive'), ...tier('alias'), ...roles(DEFAULT_THEME)]
  assertUnique(rootTokens, ':root')

  const lightNames = roles(DEFAULT_THEME).map((t) => varName(t.path))
  for (const theme of themes.filter((t) => t !== DEFAULT_THEME)) {
    assertUnique(roles(theme), `theme "${theme}"`)
    const names = new Set(roles(theme).map((t) => varName(t.path)))
    const missing = lightNames.filter((n) => !names.has(n))
    if (missing.length) throw new Error(`Theme "${theme}" is missing roles the light theme defines: ${missing.join(', ')}`)
    const extra = [...names].filter((n) => !lightNames.includes(n))
    if (extra.length) throw new Error(`Theme "${theme}" defines roles the light theme lacks: ${extra.join(', ')}`)
  }

  const lookup = (ref, from) => {
    const target = byPath.get(ref)
    if (!target) throw new Error(`Token ${from.path.join('.')} references {${ref}}, which does not exist`)
    return target
  }

  const cssValue = (token) => token.value.replace(REF, (_, ref) => `var(--${varName(lookup(ref, token).path)})`)

  const resolved = new Map()
  const resolve = (token, stack = []) => {
    const key = token.path.join('.')
    if (resolved.has(key)) return resolved.get(key)
    if (stack.includes(key)) throw new Error(`Token reference cycle: ${[...stack, key].join(' -> ')}`)
    const value = token.value.replace(REF, (_, ref) => resolve(lookup(ref, token), [...stack, key]))
    resolved.set(key, value)
    return value
  }

  // Every value is validated up front so a bad reference fails the build, not a later lookup.
  for (const t of all) resolve(t)

  const decl = (name, value) => `  --${name}: ${value};`
  const block = (selector, tokens) => [`${selector} {`, ...tokens.map((t) => decl(varName(t.path), cssValue(t))), '}']

  const css = [`/* ${HEADER} */`, '']
  css.push(...block(':root', rootTokens))
  for (const theme of themes.filter((t) => t !== DEFAULT_THEME)) {
    css.push('', ...block(`[data-theme="${theme}"]`, roles(theme)))
  }
  const entries = themeEntries(all, byPath)
  css.push('', '@theme inline {', ...entries.map(([k, v]) => decl(k, v)), '}', '')

  // The JS map holds the light theme only (plus primitives and aliases). Other themes exist
  // in CSS; JS consumers that need theme-aware colors should read the CSS variables.
  const jsTokens = {}
  for (const t of rootTokens) jsTokens[varName(t.path)] = resolve(t)
  const chartColors = roles(DEFAULT_THEME)
    .filter((t) => t.path[2] === 'chart' && /^\d+$/.test(t.path[3]))
    .sort((a, b) => Number(a.path[3]) - Number(b.path[3]))
    .map((t) => resolve(t))

  const js = [
    `// ${HEADER}`,
    '',
    `export const tokens = ${JSON.stringify(jsTokens, null, 2)}`,
    '',
    `export const chartColors = ${JSON.stringify(chartColors, null, 2)}`,
    '',
  ].join('\n')

  return { css: css.join('\n'), js, twMerge: twMergeModule(entries) }
}

// tailwind-merge only knows Tailwind's default theme. Without these values it reads text-body
// as a color (and drops it next to text-text-primary) and misses p-ds-md / p-ds-lg conflicts.
function twMergeModule(entries) {
  const scales = {}
  for (const [key] of entries) {
    if (key.includes('--')) continue // sub-properties such as --text-body--line-height
    const scale = MERGE_SCALES.find((name) => key.startsWith(`${name}-`))
    if (!scale) throw new Error(`Theme key --${key} has no tailwind-merge scale; add its namespace to MERGE_SCALES`)
    if (!scales[scale]) scales[scale] = []
    scales[scale].push(key.slice(scale.length + 1))
  }
  return [`// ${HEADER}`, '', `export const themeScales = ${JSON.stringify(scales, null, 2)}`, ''].join('\n')
}

function themeEntries(all, byPath) {
  const entries = []
  const ref = (t) => `var(--${varName(t.path)})`
  const alias = (group) => all.filter((t) => t.path[0] === 'alias' && t.path[1] === group)

  for (const t of all) {
    if (t.path[0] === 'role' && t.path[1] === DEFAULT_THEME && COLOR_ROLE_GROUPS.includes(t.path[2])) {
      entries.push([`color-${varName(t.path)}`, ref(t)])
    }
  }
  for (const t of alias('radius')) {
    const key = RADIUS_THEME[t.path[2]]
    if (key) entries.push([`radius-${key}`, ref(t)])
  }
  for (const t of alias('space')) entries.push([`spacing-ds-${t.path[2]}`, ref(t)])
  for (const t of alias('font-size')) {
    const name = t.path[2]
    entries.push([`text-${name}`, ref(t)])
    const lineHeight = byPath.get(`alias.line-height.${name}`)
    if (lineHeight) entries.push([`text-${name}--line-height`, ref(lineHeight)])
  }
  for (const t of alias('shadow')) entries.push([`shadow-${t.path[2]}`, ref(t)])
  for (const t of alias('easing')) {
    const key = EASING_THEME[t.path[2]]
    if (key) entries.push([`ease-${key}`, ref(t)])
  }
  const sans = byPath.get('primitive.font.family.sans')
  if (sans) entries.push(['font-sans', ref(sans)])
  return entries
}

function main() {
  const dir = new URL('../src/design-system/tokens/', import.meta.url)
  const source = JSON.parse(readFileSync(new URL('tokens.json', dir), 'utf8'))
  const { css, js, twMerge } = buildTokens(source)
  const outputs = [
    [new URL('tokens.css', dir), css],
    [new URL('tokens.js', dir), js],
    [new URL('../lib/twMergeConfig.js', dir), twMerge],
  ]
  for (const [url, content] of outputs) {
    writeFileSync(url, content)
    console.log(`Wrote ${fileURLToPath(url)}`)
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main()
