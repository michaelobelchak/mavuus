// srcset for a local image, from the variants listed above. Undefined when there are none.
export function srcSetFor(url) {
  const dot = url?.lastIndexOf('.') ?? -1
  if (dot < 0) return undefined
  const base = url.slice(0, dot)
  const ext = url.slice(dot)
  const widths = IMAGE_WIDTHS[base]
  if (!widths || widths.length < 2) return undefined
  return widths
    .map((w, i) => `${i === widths.length - 1 ? url : `${base}-p-${w}${ext}`} ${w}w`)
    .join(', ')
}
