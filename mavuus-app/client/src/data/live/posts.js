// srcset for a Webflow CDN image, from the variants listed above. Undefined when there are none.
export function srcSetFor(url) {
  const id = url?.match(/\/([0-9a-f]{24})_/)?.[1]
  const widths = id && IMAGE_WIDTHS[id]
  if (!widths || widths.length < 2) return undefined
  const dot = url.lastIndexOf('.')
  const base = url.slice(0, dot)
  const ext = url.slice(dot)
  return widths
    .map((w, i) => `${i === widths.length - 1 ? url : `${base}-p-${w}${ext}`} ${w}w`)
    .join(', ')
}
